# 3. FEATURE EXTRACTION (Math Helpers)
# -------------------------------
def calculate_features(data):
    """
    Computes 11 statistical features matching the Python training script.
    Order: [Mean, Std, Min, Max, Variance, RMS, Energy, IQR, Median, Skew, Kurt]
    """
    n = len(data)
    
    # 1. Mean
    mean_val = sum(data) / n
    
    # Pre-calc differences for variance/std/skew/kurt
    diffs = [x - mean_val for x in data]
    
    # 5. Variance (Used instead of Range)
    variance = sum([d**2 for d in diffs]) / n
    
    # 2. Standard Deviation
    std_val = math.sqrt(variance)
    
    # 3. Min & 4. Max
    min_val = min(data)
    max_val = max(data)
    
    # 6. RMS
    rms_val = math.sqrt(sum([x**2 for x in data]) / n)
    
    # 7. Energy
    energy_val = sum([x**2 for x in data])
    
    # Sort for Percentiles and Median
    sorted_data = sorted(data)
    
    # 8. IQR (Q3 - Q1)
    q1 = sorted_data[int(0.25 * n)]
    q3 = sorted_data[int(0.75 * n)]
    iqr_val = q3 - q1
    
    # 9. Median (Used instead of MAD)
    if n % 2 == 0:
        median_val = (sorted_data[n//2 - 1] + sorted_data[n//2]) / 2
    else:
        median_val = sorted_data[n//2]

    # 10. Skewness
    if std_val == 0:
        skew_val = 0.0
    else:
        moment3 = sum([d**3 for d in diffs]) / n
        skew_val = moment3 / (std_val**3)
        
    # 11. Kurtosis (Fisher)
    if std_val == 0:
        kurt_val = -3.0 # Default for constant signal
    else:
        moment4 = sum([d**4 for d in diffs]) / n
        kurt_val = (moment4 / (std_val**4)) - 3.0
        
    # STRICT ORDER MATCHING TRAINING CODE
    return [mean_val, std_val, min_val, max_val, variance, rms_val, 
            energy_val, iqr_val, median_val, skew_val, kurt_val]

